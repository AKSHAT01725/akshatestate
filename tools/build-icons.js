// Usage (from the site folder):  npm i --no-save @fortawesome/fontawesome-free@6.5.1  &&  node tools/build-icons.js
// Re-run this whenever you use a NEW Font Awesome icon (an <i class="fas fa-something"> that is not listed in css/icons.css).
// Build css/icons.css: the Font Awesome icons this site uses, as tiny inline SVG masks (no font or CDN download).
const fs = require("fs"), path = require("path");
const root = process.argv[2] || path.join(__dirname, "..");
const FA = path.dirname(require.resolve("@fortawesome/fontawesome-free/package.json"));
const meta = JSON.parse(fs.readFileSync(FA + "/metadata/icon-families.json", "utf8"));

// alias -> canonical name (FA6 keeps old v5 names such as map-marker-alt as aliases)
const canon = {};
for (const [name, d] of Object.entries(meta)) {
  canon[name] = name;
  for (const al of (d.aliases && d.aliases.names) || []) canon[al] = name;
}

// walk project files (exclude admin, node_modules, .git)
function walk(dir, out = []) {
  for (const f of fs.readdirSync(dir, { withFileTypes: true })) {
    if (["node_modules", ".git", "admin"].includes(f.name) || f.name.startsWith("_") || f.name === "icons.css") continue;
    const p = path.join(dir, f.name);
    if (f.isDirectory()) walk(p, out); else if (/\.(html|js|css)$/.test(f.name) && !/^admin\./.test(f.name)) out.push(p);
  }
  return out;
}
const files = walk(root);
const pairs = new Set(), names = new Set();
for (const f of files) {
  const s = fs.readFileSync(f, "utf8");
  for (const m of s.matchAll(/\b(fas|far|fab|fa-solid|fa-regular|fa-brands)\s+fa-([a-z0-9-]+)/g)) {
    const st = { fas: "solid", "fa-solid": "solid", far: "regular", "fa-regular": "regular", fab: "brands", "fa-brands": "brands" }[m[1]];
    pairs.add(st + "|" + m[2]);
  }
  for (const m of s.matchAll(/\bfa-([a-z0-9]+(?:-[a-z0-9]+)*)\b/g)) names.add(m[1]);
}
// names that appear without an adjacent style class (built in JS, e.g. ["fa-bed", ...]): choose solid, else brands
const ignore = new Set(["solid", "regular", "brands", "spin"]);
const have = (style, n) => fs.existsSync(`${FA}/svgs/${style}/${canon[n] || n}.svg`);
const styled = new Set([...pairs].map(p => p.split("|")[1]));
for (const n of names) {
  if (ignore.has(n) || styled.has(n)) continue;
  if (have("solid", n)) pairs.add("solid|" + n); else if (have("brands", n)) pairs.add("brands|" + n); else if (have("regular", n)) pairs.add("regular|" + n);
  else console.log("  (no svg for)", n);
}

let lastWidth = 1;
function svgUri(style, n) {
  const file = `${FA}/svgs/${style}/${canon[n] || n}.svg`;
  if (!fs.existsSync(file)) return null;
  let s = fs.readFileSync(file, "utf8").replace(/<!--[\s\S]*?-->/g, "").replace(/<\?xml[^>]*>/g, "").replace(/\s+/g, " ").trim();
  s = s.replace(/<svg /, '<svg xmlns="http://www.w3.org/2000/svg" ').replace(/ xmlns="http:\/\/www.w3.org\/2000\/svg"(?=[^>]*xmlns)/, "");
  const vb = (s.match(/viewBox="0 0 (\d+(?:\.\d+)?) 512"/) || [])[1];
  lastWidth = vb ? Math.round((parseFloat(vb) / 512) * 1000) / 1000 : 1;
  return "url(\"data:image/svg+xml," + encodeURIComponent(s).replace(/%20/g, " ").replace(/%3D/g, "=").replace(/%3A/g, ":").replace(/%2F/g, "/").replace(/%22/g, "'") + "\")";
}

const sel = { solid: [".fas", ".fa-solid"], regular: [".far", ".fa-regular"], brands: [".fab", ".fa-brands"] };
let css = "/* Font Awesome icons used on this site, as inline SVG masks. Generated by tools/build-icons.js from Font Awesome Free 6.5.1 (CC BY 4.0, fontawesome.com/license/free). Replaces the cdnjs stylesheet and web fonts. */\n";
css += ".fas,.far,.fab,.fa-solid,.fa-regular,.fa-brands{background-color:currentColor;-webkit-mask:var(--fa) no-repeat center/contain;mask:var(--fa) no-repeat center/contain}\n";
let count = 0, bytes = 0;
const rules = []; const widthRules = [];
for (const p of [...pairs].sort()) {
  const [style, n] = p.split("|");
  const uri = svgUri(style, n);
  if (!uri) { console.log("  (missing svg)", p); continue; }
  const selector = sel[style].map(s => `${s}.fa-${n}`).join(",");
  rules.push(`${selector}{--fa:${uri}}`); count++;
  if (lastWidth !== 1) widthRules.push(`.fa-${n}{width:${lastWidth}em}`);
}
css += rules.join("\n") + "\n";
fs.writeFileSync(path.join(root, "css/icons.css"), css);
const baseBlock = "/* icons:start (generated by tools/build-icons.js) */.fas,.far,.fab,.fa-solid,.fa-regular,.fa-brands{display:inline-block;flex:none;width:1em;height:1em;vertical-align:-.125em;font-style:normal;line-height:1}" + [...new Set(widthRules)].sort().join("") + "/* icons:end */";
const sp = path.join(root, "css/style.css");
let st = fs.readFileSync(sp, "utf8");
if (/\/\* icons:start[\s\S]*?icons:end \*\//.test(st)) st = st.replace(/\/\* icons:start[\s\S]*?icons:end \*\//, () => baseBlock);
else st = st.replace(/\s*$/, "\n") + baseBlock + "\n";
fs.writeFileSync(sp, st);
console.log("base block bytes:", baseBlock.length);
console.log("icons:", count, "| css bytes:", css.length, "| gzip approx:", require("zlib").gzipSync(css).length);
