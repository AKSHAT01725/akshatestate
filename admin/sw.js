/* Akshat Estate ADMIN app service worker (scope: /admin/ only).
   Needed so the admin can be installed as an app. Network first, so you always get the latest admin;
   the saved copy is only used if you are offline. Firebase, EmailJS and every other website are never touched. */
const CACHE = "ae-admin-v1";

self.addEventListener("install", () => self.skipWaiting());

self.addEventListener("activate", (event) => {
  event.waitUntil(
    caches.keys()
      .then((keys) => Promise.all(keys.filter((k) => k !== CACHE).map((k) => caches.delete(k))))
      .then(() => self.clients.claim())
  );
});

self.addEventListener("fetch", (event) => {
  const req = event.request;
  if (req.method !== "GET") return;
  const url = new URL(req.url);
  if (url.origin !== self.location.origin) return;          /* only this website's own files */
  event.respondWith(
    fetch(req)
      .then((res) => {
        if (res.ok) { const copy = res.clone(); caches.open(CACHE).then((c) => c.put(req, copy)); }
        return res;
      })
      .catch(() => caches.match(req).then((hit) => hit || (req.mode === "navigate" ? caches.match(new URL("./", self.location)) : Response.error())))
  );
});
